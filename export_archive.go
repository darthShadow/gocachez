package main

import (
	"bytes"
	"encoding/binary"
	"strconv"
	"strings"
)

const (
	archiveMagic               = "!<arch>\n"
	archiveHeaderLen           = 60
	pkgdefName                 = "__.PKGDEF"
	generatedSourcePrefixLimit = 64 << 10
	generatedCgoBanner         = "// Code generated by cmd/cgo; DO NOT EDIT."
	generatedCgoDirective      = "//go:cgo_"
	indexedExportVersionLimit  = 16
)

func isGeneratedCgoSource(data []byte) bool {
	if !isLikelyText(data) || !bytes.Contains(data, []byte("package ")) {
		return false
	}
	// cmd/cgo writes its generated-code banner at the start of every generated
	// source file, so the bounded classification prefix is sufficient.
	return bytes.Contains(data, []byte(generatedCgoBanner)) ||
		bytes.Contains(data, []byte(generatedCgoDirective))
}

func isIndexedExportData(data []byte) bool {
	if len(data) < 1+3 || data[0] != 'i' {
		return false
	}
	prefixComplete := len(data) < generatedSourcePrefixLimit
	data = data[1:]
	version, n := binary.Uvarint(data)
	if n <= 0 || version > indexedExportVersionLimit {
		return false
	}
	data = data[n:]
	stringSize, n := binary.Uvarint(data)
	if n <= 0 {
		return false
	}
	data = data[n:]
	declSize, n := binary.Uvarint(data)
	if n <= 0 {
		return false
	}
	data = data[n:]

	// Strings and declarations are followed by the package index. For a
	// bounded prefix, accepting a payload that extends beyond the prefix is
	// safe after the header and sizes have been validated.
	payloadSize := stringSize + declSize
	if payloadSize < stringSize {
		return false
	}
	return payloadSize < uint64(len(data)) || !prefixComplete
}

func packageArchiveExportSize(data []byte) (int64, bool) {
	if len(data) < len(archiveMagic)+archiveHeaderLen {
		return 0, false
	}
	if string(data[:len(archiveMagic)]) != archiveMagic {
		return 0, false
	}

	name, size, ok := archiveMemberHeader(data[len(archiveMagic) : len(archiveMagic)+archiveHeaderLen])
	if !ok || name != pkgdefName {
		return 0, false
	}
	return size, true
}

func archiveMemberHeader(header []byte) (string, int64, bool) {
	if len(header) < archiveHeaderLen || !bytes.Equal(header[58:60], []byte("`\n")) {
		return "", 0, false
	}
	name := strings.TrimSpace(string(header[:16]))
	name = strings.TrimSuffix(name, "/")
	size, err := strconv.ParseInt(strings.TrimSpace(string(header[48:58])), 10, 64)
	if err != nil || size < 0 {
		return "", 0, false
	}
	return name, size, true
}
